import 'dart:convert';

/// The kind of content a chat message carries.
enum MessageType {
  text,
  image,
  video,
  document,
  pdf,
  audio,
  location,
  buttons,
  list,
  form,
  note,
  template,
}

/// Where a message originated from (drives styling/badges).
enum MessageSource {
  contact, // incoming from the contact
  agent, // outgoing from a human agent (Por defecto si 'es mio' = true)
  ai, // generated by AI
  chatbot, // automated chatbot flow
  n8n, // n8n automation
}

/// Delivery state for outgoing messages.
enum MessageStatus { sending, sent, delivered, read, failed }

class Reaction {
  const Reaction({required this.emoji, required this.by});
  final String emoji;
  final String by;
}

class MessageAction {
  const MessageAction({required this.label, this.description});
  final String label;
  final String? description;
}

class Message {
  const Message({
    required this.id,
    required this.type,
    required this.source,
    required this.time,
    this.text,
    this.caption,
    this.fileName,
    this.fileSize,
    this.duration,
    this.locationName,
    this.locationAddress,
    this.actions = const [],
    this.reactions = const [],
    this.status = MessageStatus.read,
    this.urlArchivo, // Agregado para no perder la URL directa del backend
    this.templateHeaderType,
    this.templateHeaderUrl,
    this.localPath,
    this.errorText,
  });

  final String id;
  final MessageType type;
  final MessageSource source;
  final DateTime time;

  final String? text;
  final String? caption;
  final String? fileName;
  final String? fileSize;
  final String? duration; // audio/video length
  final String? locationName;
  final String? locationAddress;

  final List<MessageAction> actions; // for buttons / list rows / form fields
  final List<Reaction> reactions;
  final MessageStatus status;
  
  final String? urlArchivo; // URL generada por tu backend en getFileUrl()
  final MessageType? templateHeaderType;
  final String? templateHeaderUrl;

  /// Ruta del archivo en el teléfono mientras se envía (vista previa local, no viene del servidor).
  final String? localPath;

  /// Motivo del fallo de envío (solo mensajes locales que fallaron).
  final String? errorText;

  bool get isLocal => id.startsWith('temp_');

  Message copyWith({MessageStatus? status, String? errorText, String? localPath}) => Message(
        id: id,
        type: type,
        source: source,
        time: time,
        text: text,
        caption: caption,
        fileName: fileName,
        fileSize: fileSize,
        duration: duration,
        locationName: locationName,
        locationAddress: locationAddress,
        actions: actions,
        reactions: reactions,
        status: status ?? this.status,
        urlArchivo: urlArchivo,
        templateHeaderType: templateHeaderType,
        templateHeaderUrl: templateHeaderUrl,
        localPath: localPath ?? this.localPath,
        errorText: errorText,
      );

  bool get isOutgoing => source != MessageSource.contact;

  /// ---------------------------------------------------------------------------
  /// MAPEO DESDE TU API DE LARAVEL
  /// ---------------------------------------------------------------------------
  factory Message.fromJson(Map<String, dynamic> json) {
    // 1. Parsear el entero del tipo de Laravel (1, 2, 3...) a tu Enum
    final rawTipo = json['tipo'];
    final int parsedTipo = (rawTipo is int) ? rawTipo : int.tryParse(rawTipo?.toString() ?? '') ?? 1;
    final MessageType tipo = _mapTipo(parsedTipo);

    // 2. Parsear el entero del estado de Laravel (1, 2, 3...) a tu Enum
    final rawEstado = json['estado'];
    final int parsedEstado = (rawEstado is int) ? rawEstado : int.tryParse(rawEstado?.toString() ?? '') ?? 0;
    final MessageStatus estado = _mapEstado(parsedEstado);

    // 3. Definir el origen basado en "es mio"
    final bool esMio = json['es mio'] ?? false;
    final MessageSource source = esMio ? MessageSource.agent : MessageSource.contact;

    // 4. Extraer datos específicos del metadata de WhatsApp
    final dynamic rawMetadata = json['metadata'];
    final Map<String, dynamic> metadata = (rawMetadata is Map<String, dynamic>) ? rawMetadata : {};

    // Extraer texto (en WA interactivo, el texto a veces viene en el body del metadata)
    String? texto = json['contenido'];
    if (texto == null && metadata.containsKey('interactive')) {
      texto = metadata['interactive']?['body']?['text'];
    }

    // 5. MANEJO ESPECIAL PARA PLANTILLAS (Tipo 7) --- CORREGIDO: USAR "metadata" EN VEZ DE "meta"
    if (tipo == MessageType.template) {
      // Determinar qué hay en el header de la plantilla
      final int? tipoHeader = metadata['tipo_header'] is int 
          ? metadata['tipo_header'] 
          : int.tryParse(metadata['tipo_header']?.toString() ?? '');
      
      MessageType? headerType;
      if (tipoHeader == 2) headerType = MessageType.image;
      else if (tipoHeader == 3) headerType = MessageType.video;
      else if (tipoHeader == 4) headerType = MessageType.document;

      // Extraer botones (Laravel los guarda como string en la BD, hay que decodificarlos)
      List<MessageAction> templateButtons = [];
      final rawButtons = metadata['buttons'];
      if (rawButtons != null) {
        List<dynamic> btnList = [];
        if (rawButtons is String && rawButtons.trim().isNotEmpty) {
          try {
            btnList = jsonDecode(rawButtons);
          } catch (e) {
            btnList = [];
          }
        } else if (rawButtons is List) {
          btnList = rawButtons;
        }
            
        for (var btn in btnList) {
          templateButtons.add(MessageAction(
            label: btn['text'] ?? '',
            description: btn['type'] == 'PHONE_NUMBER' ? 'Teléfono' : (btn['url'] ?? ''),
          ));
        }
      }

      return Message(
        id: json['id']?.toString() ?? '',
        type: tipo,
        source: source,
        time: DateTime.parse(json['fecha'].toString()).toLocal(),
        text: texto,
        status: estado,
        urlArchivo: json['url_archivo'],
        templateHeaderType: headerType,
        templateHeaderUrl: metadata['header'], // CORREGIDO
        actions: templateButtons,
      );
    }

    // 6. RETORNO GENÉRICO PARA EL RESTO DE MENSAJES
    return Message(
      id: json['id']?.toString() ?? '',
      type: tipo,
      source: source,
      time: DateTime.parse(json['fecha'].toString()).toLocal(),
      text: texto,
      status: estado,
      urlArchivo: json['url_archivo'],
      
      // --- Extracción desde Metadata ---
      caption: _getCaption(tipo, metadata),
      fileName: _getFileName(tipo, metadata),
      fileSize: _getFileSize(tipo, metadata),
      duration: _getDuration(tipo, metadata),
      locationName: _getLocationName(tipo, metadata),
      locationAddress: _getLocationAddress(tipo, metadata),
      actions: _getActions(tipo, metadata),
    );
  }

  /// ---------------------------------------------------------------------------
  /// HELPERS PARA EXTRAER DATOS DEL METADATA DE WHATSAPP
  /// ---------------------------------------------------------------------------

  static String? _getCaption(MessageType tipo, Map<String, dynamic> meta) {
    if (tipo == MessageType.image && meta.containsKey('image')) return meta['image']?['caption'];
    if (tipo == MessageType.video && meta.containsKey('video')) return meta['video']?['caption'];
    return null;
  }

  static String? _getFileName(MessageType tipo, Map<String, dynamic> meta) {
    if (tipo == MessageType.document && meta.containsKey('document')) {
      return meta['document']?['original_name'] ??
          meta['document']?['filename'] ??
          meta['document']?['caption'];
    }
    return null;
  }

  static String? _getFileSize(MessageType tipo, Map<String, dynamic> meta) {
    if (tipo == MessageType.document && meta.containsKey('document')) {
      final bytes = int.tryParse(meta['document']?['file_size']?.toString() ?? '');
      if (bytes != null && bytes > 0) {
        return bytes < 1048576
            ? '${(bytes / 1024).toStringAsFixed(0)} KB'
            : '${(bytes / 1048576).toStringAsFixed(1)} MB';
      }
    }
    return null;
  }

  static String? _getDuration(MessageType tipo, Map<String, dynamic> meta) {
    if (tipo == MessageType.audio && meta.containsKey('audio')) return meta['audio']?['seconds']?.toString();
    if (tipo == MessageType.video && meta.containsKey('video')) return meta['video']?['seconds']?.toString();
    return null;
  }

  static String? _getLocationName(MessageType tipo, Map<String, dynamic> meta) {
    if (tipo == MessageType.location && meta.containsKey('location')) return meta['location']?['name'];
    return null;
  }

  static String? _getLocationAddress(MessageType tipo, Map<String, dynamic> meta) {
    if (tipo == MessageType.location && meta.containsKey('location')) return meta['location']?['address'];
    return null;
  }

  static List<MessageAction> _getActions(MessageType tipo, Map<String, dynamic> meta) {
    if (!meta.containsKey('interactive')) return [];
    
    final interactive = meta['interactive'];
    final List<MessageAction> actions = [];
    final type = interactive?['type'];

    if (type == 'button' && interactive['action']?['buttons'] != null) {
      for (var btn in interactive['action']['buttons']) {
        actions.add(MessageAction(label: btn['title'] ?? ''));
      }
    } 
    else if (type == 'list' && interactive['action']?['rows'] != null) {
      for (var row in interactive['action']['rows']) {
        actions.add(MessageAction(
          label: row['title'] ?? '', 
          description: row['description'],
        ));
      }
    }
    
    return actions;
  }

  /// ---------------------------------------------------------------------------
  /// TRADUCCIÓN DE CONSTANTES LARAVEL A ENUMS FLUTTER
  /// ---------------------------------------------------------------------------

  static MessageType _mapTipo(int tipo) {
    switch (tipo) {
      case 1:  return MessageType.text;       // TEXTO
      case 2:  return MessageType.image;      // IMAGEN
      case 3:  return MessageType.video;      // VIDEO
      case 4:  return MessageType.document;   // DOCUMENTO
      case 5:  return MessageType.location;   // LOCALIZACION
      case 6:  return MessageType.audio;      // AUDIO
      case 7:  return MessageType.template;       // PLANTILLA
      case 8:  return MessageType.note;       // CONTACTO (WhatsApp vCard)
      case 9:  return MessageType.note;       // REACCION
      case 10: return MessageType.form;       // FLOWS
      case 11: return MessageType.buttons;    // INTERACCION_BOTON
      case 12: return MessageType.list;       // INTERACCION_LISTADO
      case 13: return MessageType.image;      // STICKER (Se renderiza como imagen)
      default: return MessageType.text;
    }
  }

  static MessageStatus statusFromInt(int estado) => _mapEstado(estado);

  static MessageStatus _mapEstado(int estado) {
    switch (estado) {
      case 1: return MessageStatus.sent;      // ENVIADO
      case 2: return MessageStatus.delivered; // ENTREGADO
      case 3: return MessageStatus.read;      // LEIDO
      case 4: return MessageStatus.failed;    // FALLIDO
      case 0: 
      default: return MessageStatus.failed;   // ERROR
    }
  }

  /// ---------------------------------------------------------------------------
  /// PARA CUANDO ENVÍAS UN MENSAJE LOCALMENTE (ANTES DE QUE RESPONDA LA API)
  /// ---------------------------------------------------------------------------
  factory Message.localTemp({
    String? text,
    MessageType type = MessageType.text,
    String? localPath,
    String? fileName,
    String? caption,
  }) {
    return Message(
      id: 'temp_${DateTime.now().microsecondsSinceEpoch}',
      type: type,
      source: MessageSource.agent,
      time: DateTime.now(),
      text: text,
      caption: caption,
      fileName: fileName,
      localPath: localPath,
      status: MessageStatus.sending, // Estado especial local
    );
  }

  /// Mismo formato que entrega el servidor, para que el caché se relea con [Message.fromJson] sin perder datos.
  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'tipo': _tipoToInt(type),
      'es mio': isOutgoing,
      'contenido': text,
      'estado': _statusToInt(status),
      'fecha': time.toIso8601String(),
      'url_archivo': urlArchivo,
      'metadata': _metadataToJson(),
    };
  }

  static int _tipoToInt(MessageType t) {
    switch (t) {
      case MessageType.text: return 1;
      case MessageType.image: return 2;
      case MessageType.video: return 3;
      case MessageType.document:
      case MessageType.pdf: return 4;
      case MessageType.location: return 5;
      case MessageType.audio: return 6;
      case MessageType.template: return 7;
      case MessageType.note: return 8;
      case MessageType.form: return 10;
      case MessageType.buttons: return 11;
      case MessageType.list: return 12;
    }
  }

  Map<String, dynamic> _metadataToJson() {
    switch (type) {
      case MessageType.image:
        return {'image': {'caption': caption}};
      case MessageType.video:
        return {'video': {'caption': caption, 'seconds': duration}};
      case MessageType.document:
      case MessageType.pdf:
        return {'document': {'caption': caption, 'filename': fileName, 'original_name': fileName}};
      case MessageType.audio:
        return {'audio': {'seconds': duration}};
      case MessageType.location:
        return {'location': {'name': locationName, 'address': locationAddress}};
      case MessageType.buttons:
        return {
          'interactive': {
            'type': 'button',
            'action': {'buttons': [for (final a in actions) {'title': a.label}]},
          },
        };
      case MessageType.list:
        return {
          'interactive': {
            'type': 'list',
            'action': {'rows': [for (final a in actions) {'title': a.label, 'description': a.description}]},
          },
        };
      case MessageType.template:
        return {
          'tipo_header': switch (templateHeaderType) {
            MessageType.image => 2,
            MessageType.video => 3,
            MessageType.document => 4,
            _ => null,
          },
          'header': templateHeaderUrl,
          'buttons': [
            for (final a in actions)
              {
                'text': a.label,
                'type': a.description == 'Teléfono' ? 'PHONE_NUMBER' : 'URL',
                'url': a.description,
              },
          ],
        };
      default:
        return {};
    }
  }

  int _statusToInt(MessageStatus status) {
    switch (status) {
      case MessageStatus.sending: return 1; // Se envía como "Enviado" a la API
      case MessageStatus.sent: return 1;
      case MessageStatus.delivered: return 2;
      case MessageStatus.read: return 3;
      case MessageStatus.failed: return 4;
    }
  }
}